/*
 * Converts every binary image (including the generated GIF animations) into a
 * plain TypeScript source module with base64 data URIs.
 *
 * Why: the assets then live in `src/` as text files and are imported by the code,
 * so they are always part of the downloaded project — no external URLs, no runtime
 * downloads, and no dependence on binary files surviving an export.
 *
 * Run from the project root: node scripts/generate-asset-modules.cjs
 */
const fs = require("fs");
const path = require("path");
const { GROUPS, MIME_BY_EXTENSION } = require("./asset-map.cjs");

const root = process.cwd();

function dataUri(filePath) {
  const mime = MIME_BY_EXTENSION[path.extname(filePath).toLowerCase()];
  if (!mime) throw new Error(`Unsupported image type: ${filePath}`);
  const base64 = fs.readFileSync(filePath).toString("base64");
  return `data:${mime};base64,${base64}`;
}

const HEADER = [
  "/**",
  " * AUTO-GENERATED FILE — do not edit by hand.",
  " * Images are embedded as base64 data URIs so all visual assets ship with the source code.",
  " * Generated by `node scripts/generate-asset-modules.cjs` from the files in `public/images`.",
  " * Run `node scripts/restore-assets.cjs` to recreate those binary files from these modules.",
  " */",
  "",
].join("\n");

for (const group of GROUPS) {
  const values = new Map();

  for (const entry of group.files) {
    const source = path.join(root, group.dir, entry.file);
    if (!fs.existsSync(source)) {
      throw new Error(`Missing source asset: ${source}\nIf the binary files were not downloaded, run: node scripts/restore-assets.cjs`);
    }
    const uri = dataUri(source);

    if (group.nested) {
      if (!values.has(entry.key)) values.set(entry.key, {});
      values.get(entry.key)[entry.slot] = uri;
    } else {
      values.set(entry.key, uri);
    }
  }

  const lines = [HEADER, `export const ${group.exportName} = {`];
  for (const [key, value] of values) {
    if (group.nested) {
      lines.push(`  ${key}: {`);
      lines.push(`    animated: ${JSON.stringify(value.animated)},`);
      lines.push(`    still: ${JSON.stringify(value.still)},`);
      lines.push("  },");
    } else {
      lines.push(`  ${key}: ${JSON.stringify(value)},`);
    }
  }
  lines.push("} as const;", "");

  const destination = path.join(root, group.module);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, lines.join("\n"), "utf8");
  console.log(`${group.module}: ${(fs.statSync(destination).size / 1024).toFixed(0)} KB, ${group.files.length} assets`);
}
